import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : require('playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:5173/');
  await page.getByRole('heading', { name: '讓音符，落在指尖。' }).waitFor();
  assert.equal(await page.locator('svg.staff ellipse').count(), 30);
  await mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  // A single-pitch range makes UI assertions deterministic without exposing answers.
  await page.locator('#low').selectOption('60');
  await page.locator('#high').selectOption('60');
  await page.locator('#high').blur();
  await page.keyboard.press('2');
  await page.getByRole('status').filter({ hasText: '音域之外' }).waitFor();
  for (let i = 0; i < 30; i++) await page.keyboard.press('1');
  await page.getByRole('heading', { name: '今天的 30 個音符，完成了。' }).waitFor();
  assert.ok(await page.locator('.result').innerText().then(t => t.includes('100%')));
  await page.getByRole('button', { name: '再練習一輪 →' }).click();
  await page.getByRole('button', { name: '∞ 無限練習' }).click();
  await page.getByRole('button', { name: '∞ 無限練習' }).blur();
  for (let i = 0; i < 11; i++) await page.keyboard.press('1');
  assert.ok((await page.locator('.stats').innerText()).includes('11'));
  assert.equal(await page.locator('svg.staff ellipse').count(), 10);
  await page.getByRole('button', { name: '隱藏提示' }).click();
  assert.equal(await page.locator('.key-name').count(), 0);
  await page.getByRole('button', { name: '♫ 聲音開啟' }).click();
  await page.reload();
  await page.getByRole('button', { name: '♩ 聲音關閉' }).waitFor();
  await page.getByRole('button', { name: '30 題練習' }).click();
  await page.locator('#low').selectOption('36');
  await page.locator('#high').selectOption('84');
  await page.locator('#clef').selectOption('treble');
  await page.getByLabel('升降記號').check();
  await page.getByRole('button', { name: '顯示提示' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.ok(await page.locator('.keyboard-scroll').evaluate(el => el.scrollWidth > el.clientWidth));
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const touch = await mobile.newPage();
  await touch.goto('http://127.0.0.1:5173/');
  await touch.locator('#low').selectOption('60'); await touch.locator('#high').selectOption('60');
  await touch.getByRole('button', { name: 'C4', exact: true }).tap();
  assert.ok((await touch.locator('.stats').innerText()).includes('1'));
  await mobile.close();
  await page.setViewportSize({ width: 1440, height: 1100 });
  for (let grade = 1; grade <= 8; grade++) {
    await page.getByRole('button', { name: `Grade ${grade}`, exact: true }).click();
    assert.equal(await page.locator('.row-signature').count(), 3);
    const signatures = await page.locator('svg.staff').evaluateAll(rows => rows.map(row => row.getAttribute('data-key')));
    assert.notEqual(signatures[0], signatures[1]); assert.notEqual(signatures[1], signatures[2]);
    if (grade >= 4) {
      const accidentals = await page.locator('.accidental').allTextContents();
      assert.ok(accidentals.includes('𝄪')); assert.ok(accidentals.includes('𝄫'));
    }
  }
  await page.screenshot({ path: 'artifacts/graded-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/graded-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const midiPage = await browser.newPage();
  await midiPage.addInitScript(() => {
    const input = { id:'keyboard-1', name:'Test Keyboard', state:'connected', onmidimessage:null };
    const second = { id:'keyboard-2', name:'Second Keyboard', state:'connected', onmidimessage:null };
    const access = { inputs:new Map([[input.id,input],[second.id,second]]), onstatechange:null };
    window.testMidi = { input, second, access };
    Object.defineProperty(navigator,'requestMIDIAccess',{ value:async () => access, configurable:true });
  });
  await midiPage.goto('http://127.0.0.1:5173/');
  await midiPage.locator('#low').selectOption('60'); await midiPage.locator('#high').selectOption('60');
  await midiPage.getByRole('button', {name:'連接 MIDI',exact:true}).click();
  await midiPage.getByText('已連接 2 個輸入裝置', {exact:false}).waitFor();
  await midiPage.evaluate(() => window.testMidi.input.onmidimessage({data:new Uint8Array([0x90,60,100])}));
  assert.ok((await midiPage.locator('.stats').innerText()).includes('1'));
  await midiPage.evaluate(() => window.testMidi.input.onmidimessage({data:new Uint8Array([0x90,60,0])}));
  assert.ok((await midiPage.locator('.stats').innerText()).includes('1'));
  await midiPage.getByLabel('MIDI 輸入裝置').selectOption('keyboard-2');
  assert.equal(await midiPage.evaluate(() => window.testMidi.input.onmidimessage), null);
  await midiPage.evaluate(() => window.testMidi.second.onmidimessage({data:new Uint8Array([0x9f,60,100])}));
  assert.ok((await midiPage.locator('.stats').innerText()).includes('2'));
  await midiPage.evaluate(() => { const m = window.testMidi; m.input.state='disconnected'; m.second.state='disconnected'; m.access.onstatechange(); });
  await midiPage.getByText('未偵測到 MIDI 輸入', {exact:false}).waitFor();
  await midiPage.evaluate(() => { window.testMidi.input.state='connected'; window.testMidi.access.onstatechange(); });
  await midiPage.getByText('已連接 1 個輸入裝置', {exact:false}).waitFor();
  await midiPage.getByRole('button', {name:'中斷 MIDI',exact:true}).click();
  assert.equal(await midiPage.evaluate(() => window.testMidi.input.onmidimessage), null);
  await midiPage.evaluate(() => Object.defineProperty(navigator,'requestMIDIAccess',{value:async () => {throw new DOMException('Denied','NotAllowedError');},configurable:true}));
  await midiPage.getByRole('button', {name:'連接 MIDI',exact:true}).click();
  await midiPage.getByText('MIDI 權限被拒絕', {exact:false}).waitFor();
  await midiPage.close();
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: desktop/mobile, keyboard/touch, completion, infinite mode, persistence, Grades 1–8, row signatures, double accidentals, simulated MIDI note input/device selection/hotplug/disconnect/permission denial.');
} finally { await browser.close(); }
